export function createRewardIcon(id) {
  const [dark, mid, light, rows] = sprites[id];
  const palette = { "#": "#25363b", d: dark, m: mid, l: light, "*": "#fff0c8" };
  const canvas = document.createElement("canvas");
  canvas.className = "reward-icon";
  canvas.width = canvas.height = 12;
  canvas.setAttribute("aria-hidden", "true");
  const context = canvas.getContext("2d");
  rows.forEach((row, y) => Array.from(row).forEach((pixel, x) => {
    if (pixel === ".") return;
    context.fillStyle = palette[pixel];
    context.fillRect(x, y, 1, 1);
  }));
  return canvas;
}
